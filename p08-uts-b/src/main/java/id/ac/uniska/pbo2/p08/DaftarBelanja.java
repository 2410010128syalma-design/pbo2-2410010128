    private void tambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahButtonActionPerformed
        // TODO add your handling code here:
        String nama = namaLabel.getText().trim();
        if (nama.isEmpty()) {
            tampilkanError("Nama barang wajib diisi", namaLabel);
            return;
        }
        if (model.sudahAda(nama)) {
            tampilkanError("Barang " + nama + " sudah ada di daftar", namaLabel);
            return;
        }

        String teksHarga = hargaLabel.getText().trim();
        long harga = 0;
        boolean hargaValid = teksHarga.matches("\\d{1,8}");
        if (hargaValid) {
            harga = Long.parseLong(teksHarga);
            hargaValid = harga >= 1 && harga <= 10000000;
        }
        if (!hargaValid) {
            tampilkanError("Harga harus angka 1 sampai 10000000",  hargaLabel);
            return;
        }

        Kategori kategori = Kategori.values()[kategoriCombo.getSelectedIndex()];
        int jumlah = (Integer) jumlahSpinner.getValue();

        model.tambah(new Barang(nama, kategori, harga, jumlah));
        perbaruiRingkasan();
        resetForm();
        namaLabel.requestFocusInWindow();
    }//GEN-LAST:event_tambahButtonActionPerformed

